// Bundles what the kuro-chat function needs from content/ into
// supabase/functions/kuro-chat/content.ts (backend FR3: the function ships its own copy).
//   npm run bundle:kuro           write the file
//   node scripts/bundle-kuro-content.ts --check   exit 1 if the file is missing or out of date
// Reads, never rewrites, Claude's content: kuro-profile.md, kuro-world.md, kuro-rubric.md,
// kuro-days/day-NN.md, tools-by-day.json, variables.json (chatTurnsPerDay), strings (the bedtime
// line), stages.json (the dream nights) and those nights' lines in content/days.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { KuroContent, KuroDayContent } from "../supabase/functions/_shared/kuro/types.ts";
import { parseVariableParts } from "../supabase/functions/_shared/kuro/dayfile.ts";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = "supabase/functions/kuro-chat/content.ts";

/** Reads a file relative to the repo root; injectable for tests. */
export type Read = (rel: string) => string;
export type List = (relDir: string) => string[];

function fail(where: string, problem: string): never {
  throw new Error(`bundle-kuro-content ${where}: ${problem}`);
}

/** One `**Label:** text` line of a kuro-days file. */
function field(text: string, label: string, where: string): string {
  const m = new RegExp(`^\\*\\*${label.replace(/[()]/g, "\\$&")}:\\*\\*\\s*(.+?)\\s*$`, "m").exec(text);
  return m ? m[1]! : fail(where, `no "${label}" line`);
}

/** A `## <title>` section's text, without its heading. */
function section(text: string, title: string): string {
  const start = text.indexOf(`## ${title}`);
  if (start < 0) return "";
  const rest = text.slice(start);
  const end = rest.indexOf("\n## ", 1);
  return (end < 0 ? rest : rest.slice(0, end)).split("\n").slice(1).join("\n").trim();
}

export function parseKuroDayForFunction(text: string, label: string): KuroDayContent {
  const day = Number(/^#\s*Day\s+(\d+)\s*$/m.exec(text)?.[1] ?? fail(label, 'no "# Day N" heading'));
  return {
    day,
    idiom: field(text, "Idiom of the day (constant)", label),
    idiomZh: field(text, "Idiom of the day (zh)", label),
    stance: field(text, "Stance", label),
    recall: field(text, "Recall from earlier days", label),
    mayReveal: field(text, "May reveal today", label),
    never: section(text, "Never"),
    // The variable layer (2026-11-02): starters with minBucket, red-blue lines, layered answers.
    ...parseVariableParts(text, label),
  };
}

/** The file's text: the content, as a typed constant. */
export function bundleKuroContent(read: Read, list: List): string {
  const content = buildKuroContent(read, list);
  return `// GENERATED by scripts/bundle-kuro-content.ts (npm run bundle:kuro). Do not edit.\n// The kuro-chat function's copy of content/ (Claude's): regenerate after content changes.\nimport type { KuroContent } from "../_shared/kuro/types.ts";\n\nexport const KURO_CONTENT: KuroContent = ${JSON.stringify(content, null, 2)};\n`;
}

/** What the function bundles, read from content/. */
export function buildKuroContent(read: Read, list: List): KuroContent {
  const days: Record<string, KuroDayContent> = {};
  for (const f of list("content/kuro-days").filter((n) => /^day-\d+\.md$/.test(n)).sort()) {
    const d = parseKuroDayForFunction(read(`content/kuro-days/${f}`), f);
    days[String(d.day)] = d;
  }
  if (!Object.keys(days).length) fail("content/kuro-days", "no day files");

  const world = read("content/kuro-world.md");
  const deskFrom = Number(/Day (\d+) on:/.exec(world)?.[1] ?? fail("kuro-world.md", 'no "Day N on:" gate line'));
  const dreamsOn = Number(/Day (\d+) only:/.exec(world)?.[1] ?? fail("kuro-world.md", 'no "Day N only:" gate line'));

  const variables = JSON.parse(read("content/variables.json")) as { constants: Record<string, unknown> };
  const turnsPerDay = variables.constants.chatTurnsPerDay;
  if (typeof turnsPerDay !== "number") fail("variables.json", "constants.chatTurnsPerDay must be a number");

  const en = JSON.parse(read("content/strings/en.json")) as Record<string, string>;
  const zh = JSON.parse(read("content/strings/zh.json")) as Record<string, string>;
  const bedtime = en["kuro.bedtime"] ?? fail("strings/en.json", 'no "kuro.bedtime"');
  // The follow-up after the unreadable line (the correction 2026-11-02); none until content has it.
  const unreadable = { zh: zh["kuro.unreadable"] ?? null, en: en["kuro.unreadable"] ?? zh["kuro.unreadable"] ?? null };
  // How affinity folds, as the ending reads it.
  const num = (k: string, d: number) => (typeof variables.constants[k] === "number" ? (variables.constants[k] as number) : d);
  const stagesAll = JSON.parse(read("content/stages.json")) as { tenderDay?: { day?: number } };
  const affinity = {
    perPoint: num("affinityPerPoint", 5),
    threshold: num("affinityThreshold", 60),
    tenderDays: typeof stagesAll.tenderDay?.day === "number" ? [stagesAll.tenderDay.day] : [],
    tenderMultiplier: num("tenderDayAffinityMultiplier", 1),
  };

  const stages = JSON.parse(read("content/stages.json")) as { dreamNights?: { nights?: number[] } };
  const dreams: Record<string, string[]> = {};
  for (const night of stages.dreamNights?.nights ?? []) {
    const file = `content/days/day-${String(night).padStart(2, "0")}.json`;
    const d = JSON.parse(read(file)) as { beats?: { night?: { say?: { t: string }[] } } };
    dreams[String(night)] = (d.beats?.night?.say ?? []).map((l) => l.t);
  }

  const tools = (JSON.parse(read("content/tools-by-day.json")) as { byDay: Record<string, string[]> }).byDay;

  return {
    profile: read("content/kuro-profile.md").trim(),
    world: world.trim(),
    rubric: read("content/kuro-rubric.md").trim(),
    days,
    bedtime,
    turnsPerDay,
    gate: { deskFrom, dreamsOn },
    dreams,
    tools,
    affinity,
    unreadable,
  };
}

const read: Read = (rel) => readFileSync(`${ROOT}${rel}`, "utf8");
const list: List = (rel) => readdirSync(`${ROOT}${rel}`);

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = bundleKuroContent(read, list);
  if (process.argv.includes("--check")) {
    const ok = existsSync(`${ROOT}${OUT}`) && readFileSync(`${ROOT}${OUT}`, "utf8") === text;
    if (!ok) console.error(`${OUT} is missing or out of date: run npm run bundle:kuro`);
    process.exitCode = ok ? 0 : 1;
  } else {
    writeFileSync(`${ROOT}${OUT}`, text);
    console.log(`wrote ${OUT}`);
  }
}
