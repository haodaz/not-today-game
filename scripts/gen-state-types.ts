// Generates src/state/types.gen.ts (the typed State) from content/variables.json.
//   node scripts/gen-state-types.ts           write the file
//   node scripts/gen-state-types.ts --check   exit 1 if the file is out of date
// The table is Claude's and is only read here. Nothing in the output is hand-written.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

type Table = Record<string, unknown>;

interface Entry {
  type: string;
  values?: string[];
  of?: string[];
  fields?: Record<string, string>;
}

const OUT = new URL("../src/state/types.gen.ts", import.meta.url);
const TABLE = new URL("../content/variables.json", import.meta.url);

/** Splits on `sep` at nesting depth 0 (ignores separators inside <> and {}). */
function splitTop(text: string, sep: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let current = "";
  for (const ch of text) {
    if (ch === "<" || ch === "{") depth++;
    if (ch === ">" || ch === "}") depth--;
    if (ch === sep && depth === 0) {
      parts.push(current);
      current = "";
    } else {
      current += ch;
    }
  }
  parts.push(current);
  return parts.map((part) => part.trim());
}

const literal = (value: string): string => JSON.stringify(value);

/** Parenthesises a union so `[]` applies to all of it. */
const wrap = (type: string): string => (type.includes(" | ") ? `(${type})` : type);

/** Maps the table's compact type notation (e.g. `map<day, {taken: bool}>`) to a TypeScript type. */
function toTs(notation: string): string {
  const text = notation.trim();
  const union = splitTop(text, "|");
  if (union.length > 1) return union.map(toTs).join(" | ");

  if (text === "null") return "null";
  if (text === "bool") return "boolean";
  if (text === "string") return "string";
  if (/^(int|number|day|dayNumber)(\s|$)/.test(text)) return "number";
  // Inside a field or map value, a bare `object` is an object id such as "chick".
  if (text === "object") return "string";

  const generic = /^(map|list|set)<(.*)>$/s.exec(text);
  if (generic) {
    const [, kind, inner] = generic as unknown as [string, string, string];
    if (kind === "map") {
      // `map<key, value>`: keys are always strings in JSON; the value part may contain commas.
      const [, ...value] = splitTop(inner, ",");
      return `Record<string, ${value.length ? toTs(value.join(", ")) : "unknown"}>`;
    }
    return `${wrap(toTs(inner))}[]`;
  }

  if (text.startsWith("{") && text.endsWith("}")) {
    const members = splitTop(text.slice(1, -1), ",").map((member) => {
      const colon = member.indexOf(":");
      // `{day,who,text}` names the keys without types; the value types are left open.
      return colon === -1
        ? `${member}: unknown`
        : `${member.slice(0, colon).trim()}: ${toTs(member.slice(colon + 1))}`;
    });
    return `{ ${members.join("; ")} }`;
  }

  // A bare word in a union such as `she|he|null` is a string literal.
  return literal(text);
}

function entryToTs(entry: Entry): string {
  const head = entry.type.split("<")[0] ?? entry.type;
  switch (head) {
    case "enum":
      return (entry.values ?? []).map(literal).join(" | ");
    case "set":
    case "subset":
      return entry.of ? `(${entry.of.map(literal).join(" | ")})[]` : toTs(entry.type);
    case "object":
      return entry.fields
        ? `{ ${Object.entries(entry.fields)
            .map(([name, type]) => `${name}: ${toTs(type)}`)
            .join("; ")} }`
        : "Record<string, unknown>";
    default:
      return toTs(entry.type);
  }
}

/** The full text of types.gen.ts for a given variable table. Pure. */
export function generate(table: Table): string {
  const names = Object.keys(table).filter((key) => key !== "constants" && !key.startsWith("_"));
  const lines = names.map((name) => `  ${name}: ${entryToTs(table[name] as Entry)};`);
  return [
    "// DO NOT EDIT. Generated by scripts/gen-state-types.ts from content/variables.json.",
    "// Run `npm run gen:state` after the table changes.",
    "",
    "export interface State {",
    ...lines,
    "}",
    "",
    "export type StateKey = keyof State;",
    "",
  ].join("\n");
}

function main(): void {
  const text = generate(JSON.parse(readFileSync(TABLE, "utf8")) as Table);
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUT, "utf8");
    if (current !== text) {
      console.error("src/state/types.gen.ts is out of date. Run `npm run gen:state`.");
      process.exit(1);
    }
    return;
  }
  writeFileSync(OUT, text);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
