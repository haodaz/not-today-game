def lay(q, t): return f'- unlock: q{q} → low: "{t[0]}" | mid: "{t[1]}" | high: "{t[2]}"'
def off(k, t): return f'- {"free text" if k == "free" else "q%s" % k} → "{t}"'

def check(day, text):
    eng_l = set(int(x) for x in re.findall(r"^- unlock: q(\d+) → low:", text.split("## Layered answers")[1].split("\n## ")[0], re.M)) if "## Layered answers" in text else set()
    off_sec = text.split("## Offline answers")[1].split("\n## ")[0]
    eng_o = set(x for x in re.findall(r"^- (q\d+|free text) →", off_sec, re.M))
    zl = set(L.get(day, {}).keys()); zo = set(("free text" if k == "free" else f"q{k}") for k in O[day])
    assert eng_l == zl, (day, "layered", eng_l, zl)
    assert eng_o == zo, (day, "offline", eng_o, zo)

def install():
    for day in range(1, 19):
        p = f"{ROOT}/day-{day:02d}.md"; s = io.open(p, encoding="utf8").read(); check(day, s)
        s = re.sub(r"\n## Layered answers \(zh\)\n.*?(?=\n## |\Z)", "", s, flags=re.S)
        s = re.sub(r"\n## Offline answers \(zh\)\n.*?(?=\n## |\Z)", "", s, flags=re.S)
        add = ""
        if L.get(day): add += "\n## Layered answers (zh)\n\n" + "\n".join(lay(q, t) for q, t in sorted(L[day].items())) + "\n"
        add += "\n## Offline answers (zh)\n\n" + "\n".join(off(k, t) for k, t in O[day].items()) + "\n"
        i = s.index("\n## Never") if "\n## Never" in s else len(s)
        s = s[:i].rstrip("\n") + "\n" + add + s[i:]
        io.open(p, "w", encoding="utf8").write(s)
    print("zh answers installed")

