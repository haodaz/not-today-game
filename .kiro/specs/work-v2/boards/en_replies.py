def install(days):
    for day in days:
        d, zh = extract(day); en = EN[day]
        assert len(zh) == len(en), (day, len(zh), len(en))
        M = dict(zip(zh, en))
        out = copy.deepcopy(d)
        def walk(o):
            if isinstance(o, dict):
                for k, v in o.items():
                    if k in ("text", "inner") and isinstance(v, str) and v in M: o[k] = M[v]
                    else: walk(v)
            elif isinstance(o, list): [walk(x) for x in o]
        walk(out)
        io.open(f"{ROOT}/en/day-{day:02d}.json", "w", encoding="utf8").write(json.dumps(out, ensure_ascii=False, indent=2) + "\n")
        print("en replies day", day, len(en))

