import json, io, re, sys, copy
ROOT = "/Users/aisandbox/Documents/holloween/not-today-game/content/replies"
HAN = re.compile(r"[一-鿿]")

def extract(day):
    d = json.load(io.open(f"{ROOT}/day-{day:02d}.json", encoding="utf8")); seen = []
    def walk(o):
        if isinstance(o, dict):
            for k, v in o.items():
                if k in ("text", "inner") and isinstance(v, str) and HAN.search(v):
                    if v not in seen: seen.append(v)
                else: walk(v)
        elif isinstance(o, list): [walk(x) for x in o]
    walk(d); return d, seen

