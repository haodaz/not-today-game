// Shapes shared by the kuro-chat function, the client and the tests (backend / kuro-chat specs).
// Pure TypeScript: no Deno, no Node, no Vite. Imports between these modules carry `.ts` (Deno).

/** One event as sent to the function: its log id (`ev<index>`), day, kind and fields. */
export interface LogEvent {
  readonly id: string;
  readonly day: number;
  readonly kind: string;
  readonly [field: string]: unknown;
}

/** The player's language, sent with every call (correction 2026-11-01). */
export type ChatLocale = "zh" | "en";

export interface MemoryTurn {
  readonly day: number;
  readonly who: "player" | "kuro";
  readonly text: string;
  /** Kuro's offline answer (no model, or the model failed). */
  readonly offline?: boolean;
  /**
   * 大失败 (the d100's flicker): the player asked, the answer was never given. Kept so the judgement
   * may cite that they asked; left out of every prompt's memory. Counts as a turn.
   */
  readonly forgotten?: true;
  /** The day's taboo fired on this turn (one per day). */
  readonly taboo?: Taboo;
}

/** Kuro's opinion of the player, never a number (kuro-chat addition 2026-11-02). */
export type Bucket = "low" | "mid" | "high";

/** What a generous answer costs the player (the taboo addition); the client plays it. */
export type Taboo = "blood" | "blur" | "flicker" | "errors";

/** A starter question (`## Starter questions`); `minBucket` low unless content says otherwise. */
export interface StarterContent {
  readonly n: number;
  readonly zh: string;
  readonly en: string;
  readonly hard: boolean;
  readonly minBucket: Bucket;
}

/** A red-blue line: said verbatim when its starter is asked. */
export interface LockedLine {
  readonly unlock: number;
  readonly text: string;
}

/** `## Layered answers`: one locked line per bucket; the high one may carry a taboo. */
export interface LayeredAnswer {
  readonly unlock: number;
  readonly low: string;
  readonly mid: string;
  readonly high: string;
  readonly taboo?: Taboo;
}

export interface Memory {
  readonly summary: string;
  readonly turns: readonly MemoryTurn[];
}

/** A day's file in content/kuro-days, as the function needs it. */
export interface KuroDayContent {
  readonly day: number;
  /** The English idiom (`Idiom of the day (constant)`), said verbatim in English. */
  readonly idiom: string;
  /** The Chinese idiom (`Idiom of the day (zh)`), said verbatim in Chinese. */
  readonly idiomZh: string;
  readonly stance: string;
  readonly recall: string;
  readonly mayReveal: string;
  readonly never: string;
  /** The variable layer's parts (absent in a bundle made before 2026-11-02: no locked answers). */
  readonly starters?: readonly StarterContent[];
  readonly locked?: readonly LockedLine[];
  readonly layered?: readonly LayeredAnswer[];
}

/** Everything the function bundles (generated by scripts/bundle-kuro-content.ts). */
export interface KuroContent {
  readonly profile: string;
  readonly world: string;
  readonly rubric: string;
  readonly days: Readonly<Record<string, KuroDayContent>>;
  /** The bedtime cap (a constant line, never generated). */
  readonly bedtime: string;
  readonly turnsPerDay: number;
  /** kuro-world.md's gate: the desk from this day on; the dreams on this day only. */
  readonly gate: { readonly deskFrom: number; readonly dreamsOn: number };
  /** The dream nights' lines (content/days night beats), by night. */
  readonly dreams: Readonly<Record<string, readonly string[]>>;
  /** content/tools-by-day.json. */
  readonly tools: Readonly<Record<string, readonly string[]>>;
  /**
   * How affinity folds, exactly as the game's ending reads it (content/variables.json and
   * stages.json): points per score, the ending's threshold (the high bucket), the tender day(s)
   * and their multiplier. Absent in an older bundle: the bucket is then low.
   */
  readonly affinity?: { readonly perPoint: number; readonly threshold: number; readonly tenderDays: readonly number[]; readonly tenderMultiplier: number };
  /** The locked follow-up after the unreadable line (strings `kuro.unreadable`), by locale; null when content has none. */
  readonly unreadable?: { readonly zh: string | null; readonly en: string | null };
}

/** A stored judgement row, as the bucket reads it (the client writes `delta` after its fold). */
export interface StoredJudgement {
  readonly day: number;
  readonly truth: number;
  readonly values: number;
  readonly bond: number;
  readonly delta?: number | null;
}

/** The end-of-beat assessment (kuro-chat FR4). */
export interface Judgement {
  readonly truth: number;
  readonly values: number;
  readonly bond: number;
  readonly evidence: readonly { readonly eventId: string; readonly note: string }[];
  /** The running memory summary, rewritten at the end of the beat (≤ 600 chars). */
  readonly summary?: string;
}

/** What the function returns. */
export type ChatResponse =
  | {
      readonly mode: "turn";
      /** Empty on a flicker (the reply is never shown). */
      readonly reply: string;
      readonly turnsLeft: number;
      readonly bedtime?: boolean;
      /** The consequence the client plays after (or instead of) the reply; null almost always. */
      readonly taboo: Taboo | null;
    }
  | { readonly mode: "judge"; readonly judgement: Judgement };
